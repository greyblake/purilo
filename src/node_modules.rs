// Cleans up node_modules directories of JavaScript projects under the home directory.
//
// The locate database is usually built as an unprivileged user that can't read home
// directories, so projects are found by walking $HOME instead.
// A node_modules directory is removed only when:
// - it sits next to package.json and a lockfile, so the package manager can restore it exactly;
// - no running process uses files in the project;
// - nothing in it changed for MIN_IDLE.

use std::collections::HashSet;
use std::ffi::OsStr;
use std::fs;
use std::io;
use std::os::unix::ffi::OsStrExt;
use std::path::{Path, PathBuf};
use std::process;
use std::time::{Duration, SystemTime};

use crate::non_empty_env;

const MIN_IDLE: Duration = Duration::from_secs(24 * 60 * 60);

const LOCKFILES: [&str; 6] = [
    "package-lock.json",
    "npm-shrinkwrap.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "bun.lock",
    "bun.lockb",
];

// Directories with these names are not searched for projects.
const SKIPPED_DIR_NAMES: [&str; 2] = ["node_modules", "target"];

pub fn clean() {
    let Some(home) = non_empty_env("HOME") else {
        return;
    };
    let projects = find_projects(&home);
    if projects.is_empty() {
        return;
    }

    let paths_in_use = match paths_in_use() {
        Ok(paths) => paths,
        Err(err) => {
            println!("Skipped node_modules: cannot tell which files are in use: {err}");
            return;
        }
    };

    let mut kept_in_use = 0;
    for project in projects {
        if paths_in_use.iter().any(|path| path.starts_with(&project)) {
            kept_in_use += 1;
            continue;
        }
        let node_modules = project.join("node_modules");
        if !is_idle(&node_modules) {
            continue;
        }

        match fs::remove_dir_all(&node_modules) {
            Ok(()) => println!("Cleaned {}", node_modules.display()),
            Err(err) => println!("Failed to clean {}: {err}", node_modules.display()),
        }
    }

    if kept_in_use > 0 {
        println!(
            "Kept {kept_in_use} node_modules directories of projects used by running processes"
        );
    }
}

// Directories with package.json, a lockfile and a node_modules directory (not a symlink).
// Hidden directories, ~/snap and SKIPPED_DIR_NAMES are not searched. Symlinks are not followed.
fn find_projects(home: &Path) -> Vec<PathBuf> {
    let home_snap = home.join("snap");
    let mut projects = Vec::new();
    let mut dirs = vec![home.to_path_buf()];

    while let Some(dir) = dirs.pop() {
        let Ok(entries) = fs::read_dir(&dir) else {
            continue;
        };
        let mut has_package_json = false;
        let mut has_lockfile = false;
        let mut has_node_modules = false;

        for entry in entries.filter_map(Result::ok) {
            let Ok(file_type) = entry.file_type() else {
                continue;
            };
            let name = entry.file_name();
            let name = name.to_string_lossy();

            if file_type.is_dir() {
                has_node_modules |= name == "node_modules";
                let path = entry.path();
                if !name.starts_with('.')
                    && !SKIPPED_DIR_NAMES.contains(&name.as_ref())
                    && path != home_snap
                {
                    dirs.push(path);
                }
            } else if file_type.is_file() {
                has_package_json |= name == "package.json";
                has_lockfile |= LOCKFILES.contains(&name.as_ref());
            }
        }

        if has_package_json && has_lockfile && has_node_modules {
            projects.push(dir);
        }
    }
    projects
}

// Working directories, executables, open files, memory-mapped files and absolute
// command line arguments of running processes, except this one.
// Processes of other users can't be inspected and are left out.
fn paths_in_use() -> io::Result<HashSet<PathBuf>> {
    let own_pid = process::id().to_string();
    let mut paths = HashSet::new();

    for entry in fs::read_dir("/proc")? {
        let entry = entry?;
        let pid = entry.file_name();
        let pid = pid.to_string_lossy();
        if !pid.bytes().all(|b| b.is_ascii_digit()) || pid == own_pid {
            continue;
        }
        let proc_dir = entry.path();

        paths.extend(fs::read_link(proc_dir.join("cwd")));
        paths.extend(fs::read_link(proc_dir.join("exe")));
        if let Ok(fds) = fs::read_dir(proc_dir.join("fd")) {
            paths.extend(
                fds.filter_map(Result::ok)
                    .filter_map(|fd| fs::read_link(fd.path()).ok()),
            );
        }
        if let Ok(cmdline) = fs::read(proc_dir.join("cmdline")) {
            paths.extend(
                cmdline
                    .split(|&b| b == 0)
                    .filter(|arg| arg.starts_with(b"/"))
                    .map(|arg| PathBuf::from(OsStr::from_bytes(arg))),
            );
        }
        // The path is the last column, and the only one that contains '/'.
        if let Ok(maps) = fs::read_to_string(proc_dir.join("maps")) {
            paths.extend(
                maps.lines()
                    .filter_map(|line| line.find('/').map(|start| PathBuf::from(&line[start..]))),
            );
        }
    }
    Ok(paths)
}

// Whether node_modules and its direct entries didn't change for MIN_IDLE.
// Installing packages and tool caches (e.g. node_modules/.vite) change them;
// walking the whole tree would be slow. Anything that can't be checked counts as changed.
fn is_idle(node_modules: &Path) -> bool {
    let Some(cutoff) = SystemTime::now().checked_sub(MIN_IDLE) else {
        return false;
    };
    let changed_before_cutoff = |path: &Path| {
        fs::symlink_metadata(path)
            .and_then(|metadata| metadata.modified())
            .is_ok_and(|mtime| mtime < cutoff)
    };
    let Ok(entries) = fs::read_dir(node_modules) else {
        return false;
    };
    changed_before_cutoff(node_modules)
        && entries
            .into_iter()
            .all(|entry| entry.is_ok_and(|entry| changed_before_cutoff(&entry.path())))
}
