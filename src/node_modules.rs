// Removes node_modules of JavaScript projects under the home directory, by the rules in
// `projects`. The lockfile lets the package manager restore them exactly.

use crate::disk_usage::{self, DiskUsage};
use crate::progress::Progress;
use crate::projects::{self, Kind};
use crate::report::Section;

const TITLE: &str = "node_modules";

const JS: Kind = Kind {
    output: "node_modules",
    manifest: "package.json",
    lockfiles: &[
        "package-lock.json",
        "npm-shrinkwrap.json",
        "yarn.lock",
        "pnpm-lock.yaml",
        "bun.lock",
        "bun.lockb",
    ],
};

pub fn clean(usage: &mut DiskUsage, progress: &Progress) -> Section {
    projects::clean(TITLE, &JS, usage, progress, |_, node_modules| {
        disk_usage::remove_dir_all(node_modules)
    })
}
